/**
 * Storage helpers for Pinned and Recent facilities
 */
export const PINNED_STORAGE_KEY = "mesh_pinned_facilities";
export const RECENT_STORAGE_KEY = "mesh_recent_facilities";
export const ACTIVE_FACILITY_STORAGE_KEY = "mesh_active_facility";

// Default pinned facilities for high-value immediate demo presence
export const DEFAULT_PINNED_IDS = ["fac-us-ord-01", "fac-de-fra-01", "fac-sg-sin-01"];

export function getStoredFacilityIds(key: string): string[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(key);
    if (!raw) return key === PINNED_STORAGE_KEY ? DEFAULT_PINNED_IDS : [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return key === PINNED_STORAGE_KEY ? DEFAULT_PINNED_IDS : [];
  }
}

export function savePinnedFacilityIds(ids: string[]): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(PINNED_STORAGE_KEY, JSON.stringify(ids));
  } catch (err) {
    console.error("Failed to save pinned facilities:", err);
  }
}

export function saveRecentFacilityIds(ids: string[]): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(RECENT_STORAGE_KEY, JSON.stringify(ids.slice(0, 10)));
  } catch (err) {
    console.error("Failed to save recent facilities:", err);
  }
}

export function addRecentFacilityId(id: string): string[] {
  const current = getStoredFacilityIds(RECENT_STORAGE_KEY);
  const next = [id, ...current.filter((item) => item !== id)].slice(0, 10);
  saveRecentFacilityIds(next);
  return next;
}

export function togglePinnedFacilityId(id: string): string[] {
  const current = getStoredFacilityIds(PINNED_STORAGE_KEY);
  const isPinned = current.includes(id);
  const next = isPinned ? current.filter((item) => item !== id) : [id, ...current];
  savePinnedFacilityIds(next);
  return next;
}

/**
 * Dynamically enriches the 115+ global facility catalog with authentic
 * companies retrieved from useCompany().companies.
 */
export function enrichFacilitiesCatalog(companies: Company[]): Facility[] {
  // If no companies, return base global facilities
  if (!companies || companies.length === 0) {
    return BASE_GLOBAL_FACILITIES;
  }

  // Convert real database companies to primary facilities
  const companyFacilities: Facility[] = companies.map((c, index) => {
    const groupCountry = c.companyGroup?.country || "United States";
    const nameLower = c.companyName.toLowerCase();

    let region: FacilityRegion = "Americas";
    let countryCode = "US";
    let flag = "🇺🇸";

    if (groupCountry.includes("Germany") || groupCountry.includes("DE") || nameLower.includes("celestia")) {
      region = "EMEA";
      countryCode = "DE";
      flag = "🇩🇪";
    } else if (groupCountry.includes("Sweden") || nameLower.includes("nordic")) {
      region = "EMEA";
      countryCode = "SE";
      flag = "🇸🇪";
    } else if (groupCountry.includes("Singapore") || nameLower.includes("asia")) {
      region = "APAC";
      countryCode = "SG";
      flag = "🇸🇬";
    }

    let type: FacilityType = "Distribution Center (DC)";
    if (nameLower.includes("cold") || nameLower.includes("polar")) {
      type = "Cold Storage";
    } else if (nameLower.includes("robotics") || nameLower.includes("hardware") || nameLower.includes("systems")) {
      type = "Assembly Plant";
    } else if (nameLower.includes("freight") || nameLower.includes("pacific")) {
      type = "Cross-Dock";
    }

    return {
      id: c.companyId,
      name: c.companyName,
      code: c.companyCode,
      city: c.companyDomain?.split(".")[0]?.toUpperCase() || `HQ-${index + 1}`,
      country: groupCountry,
      countryCode,
      flag,
      region,
      type,
      capacity: "Tenant Operating Entity",
      throughput: "Multi-Tenant Grid",
      companyId: c.companyId,
      isRealCompany: true,
    };
  });

  // Distribute real companyIds among base facilities so selecting any facility
  // correctly establishes tenant context in CompanyContext
  const enrichedBase: Facility[] = BASE_GLOBAL_FACILITIES.map((fac, idx) => {
    const mappedCompany = companies[idx % companies.length];
    return {
      ...fac,
      companyId: mappedCompany ? mappedCompany.companyId : undefined,
    };
  });

  // Return real companies followed by enriched facilities
  return [...companyFacilities, ...enrichedBase];
}
